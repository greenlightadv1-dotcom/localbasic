export async function getExecutiveData(ctx: TenantContext, opts: { from: Date; to: Date; allBranches: boolean }): Promise<ExecutiveData> {
  const branch = opts.allBranches ? null : ctx.branchId;
  const w = { p_org: ctx.organizationId, p_branch: branch, p_from: opts.from.toISOString(), p_to: opts.to.toISOString() };
  const supabase = createSupabaseServerClient();
  const [kpis, basket, sos, hourly, rfm, variance, changes, alerts, campaigns, settings] = await Promise.all([
    rpc('restaurant_executive_kpis', w, 'kpis'),
    rpc('restaurant_market_basket', { ...w, p_min_together: 2 }, 'basket'),
    rpc('restaurant_sos_stages', w, 'sos'),
    rpc('restaurant_sos_hourly', w, 'sosHourly'),
    rpc('restaurant_rfm_customers', { p_org: ctx.organizationId, p_days: 365 }, 'rfm'),
    rpc('restaurant_food_cost_variance', { p_org: ctx.organizationId, p_since: opts.from.toISOString() }, 'variance'),
    rpc('restaurant_ingredient_price_changes', { p_org: ctx.organizationId, p_since: opts.from.toISOString() }, 'priceChanges'),
    supabase.from('restaurant_margin_alerts')
      .select('id, variant_id, price_cents, cost_cents, margin_bp, floor_bp, opened_margin_bp, cause_item_id, opened_at, acknowledged_at')
      .eq('organization_id', ctx.organizationId).eq('status', 'open').order('margin_bp').limit(100),
    supabase.from('restaurant_campaigns')
      .select('id, name, segment, channel, promo_code, recipients, skipped_recent, auto_generated, created_at')
      .eq('organization_id', ctx.organizationId).order('created_at', { ascending: false }).limit(20),
    supabase.from('restaurant_analytics_settings').select('*').eq('organization_id', ctx.organizationId).maybeSingle(),
  ]);
  if (alerts.error) throw toDataUnavailable(alerts.error, 'alerts');

  // Names for the alerts' dishes and causes.
  const variantIds = (alerts.data ?? []).map((a) => a.variant_id);
  const itemIds = (alerts.data ?? []).map((a) => a.cause_item_id).filter(Boolean) as string[];
  const [variants, items, deliveries] = await Promise.all([
    variantIds.length ? supabase.from('restaurant_variants').select('id, name, product_id, restaurant_products(name)').in('id', variantIds) : Promise.resolve({ data: [] }),
    itemIds.length ? supabase.from('inventory_items').select('id, name').in('id', itemIds) : Promise.resolve({ data: [] }),
    campaignDelivery((campaigns.data ?? []).map((c) => c.id)),
  ]);
  const vName = new Map(((variants.data ?? []) as unknown as { id: string; name: string; restaurant_products: { name: string } | null }[])
    .map((v) => [v.id, v.name && v.name !== 'default' ? `${v.restaurant_products?.name ?? ''} — ${v.name}` : v.restaurant_products?.name ?? '—']));
  const iName = new Map(((items.data ?? []) as { id: string; name: string }[]).map((i) => [i.id, i.name]));

  const k = kpis as Record<string, unknown>;
  const s = settings.data;
  return {
    kpis: {
      orders: num(k.orders), netRevenueCents: num(k.net_revenue_cents), cogsCents: num(k.cogs_cents), wasteCents: num(k.waste_cents),
      wasteManualCents: num(k.waste_manual_cents), laborCents: num(k.labor_cents), opexCents: num(k.opex_cents),
      inventoryNowCents: num(k.inventory_now_cents), inventoryStartCents: num(k.inventory_start_cents), days: num(k.days),
      grossCents: num(k.gross_cents), taxCents: num(k.tax_cents), discountCents: num(k.discount_cents), refundCents: num(k.refund_cents),
      suppliesCents: num(k.supplies_cents),
    },
    basket: ((basket ?? []) as Rows).map((r) => ({
      aId: String(r.out_a_product), aName: String(r.out_a_name), bId: String(r.out_b_product), bName: String(r.out_b_name),
      together: num(r.out_together), aOrders: num(r.out_a_orders), bOrders: num(r.out_b_orders), totalOrders: num(r.out_total_orders),
      support: num(r.out_support), confAB: num(r.out_conf_a_b), confBA: num(r.out_conf_b_a), lift: num(r.out_lift),
    })),
    sos: ((sos ?? []) as Rows).map((r) => ({
      type: String(r.out_type), stage: r.out_stage as SosStage, n: num(r.out_n), avgS: num(r.out_avg_s), p50S: num(r.out_p50_s), p90S: num(r.out_p90_s),
    })),
    hourly: ((hourly ?? []) as Rows).map((r) => ({ hour: num(r.out_hour), orders: num(r.out_orders), avgReadyS: num(r.out_avg_ready_s), p90ReadyS: num(r.out_p90_ready_s) })),
    rfm: ((rfm ?? []) as Rows).map((r) => ({
      phoneKey: String(r.out_phone_key), phone: String(r.out_phone), name: (r.out_name as string) ?? null,
      firstOrderAt: String(r.out_first_order_at), lastOrderAt: String(r.out_last_order_at), orders: num(r.out_orders),
      monetaryCents: num(r.out_monetary_cents), deliveryOrders: num(r.out_delivery_orders), lastContactedAt: (r.out_last_contacted_at as string) ?? null,
    })),
    variance: ((variance ?? []) as Rows).map((r) => {
      const product = String(r.out_product_name); const variant = String(r.out_variant_name);
      return {
        variantId: String(r.out_variant_id), name: variant && variant !== 'default' && variant !== product ? `${product} — ${variant}` : product,
        categoryName: (r.out_category_name as string) ?? null, priceCents: num(r.out_price_cents), baselineCost: num(r.out_baseline_cost),
        bookCost: num(r.out_book_cost), liveCost: num(r.out_live_cost), lines: num(r.out_lines), missing: Boolean(r.out_missing),
      };
    }),
    priceChanges: ((changes ?? []) as Rows).map((r) => ({
      itemId: String(r.out_item_id), name: String(r.out_name), unit: String(r.out_unit), before: opt(r.out_price_before), now: opt(r.out_price_now),
      avgCost: num(r.out_avg_cost), purchases: num(r.out_purchases), usedIn: num(r.out_used_in),
    })),
    alerts: (alerts.data ?? []).map((a) => ({
      id: a.id, variantId: a.variant_id, name: vName.get(a.variant_id) ?? '—', priceCents: num(a.price_cents), costCents: num(a.cost_cents),
      marginBp: a.margin_bp, floorBp: a.floor_bp, openedMarginBp: a.opened_margin_bp,
      causeItem: a.cause_item_id ? iName.get(a.cause_item_id) ?? null : null, openedAt: a.opened_at, acknowledged: Boolean(a.acknowledged_at),
    })),
    campaigns: (campaigns.data ?? []).map((c) => ({
      id: c.id, name: c.name, segment: c.segment, channel: c.channel, promoCode: c.promo_code, recipients: c.recipients,
      skippedRecent: c.skipped_recent, autoGenerated: c.auto_generated, createdAt: c.created_at,
      sent: deliveries.get(c.id)?.sent ?? 0, failed: deliveries.get(c.id)?.failed ?? 0, pending: deliveries.get(c.id)?.pending ?? 0,
    })),
    settings: {
      marginFloorBp: s?.margin_floor_bp ?? 6500, lapseDays: s?.lapse_days ?? 14, autoReengage: s?.auto_reengage ?? false,
      channel: s?.reengage_channel ?? 'whatsapp', discountBp: s?.reengage_discount_bp ?? 1000, validDays: s?.reengage_valid_days ?? 14,
      message: s?.reengage_message ?? null, lastRunAt: s?.last_reengage_run_at ?? null,
    },
  };
}

/**
 * Outbox status per campaign. The outbox is readable to notification.read;
 * the dashboard reader already passed restaurant.analytics.executive, so the
 * counts (never the messages) are summed server-side for these campaign ids.
 */
async function campaignDelivery(ids: string[]): Promise<Map<string, { sent: number; failed: number; pending: number }>> {
  const out = new Map<string, { sent: number; failed: number; pending: number }>();
  if (!ids.length) return out;
  const admin = createSupabaseAdminClient();
  const { data } = await admin.from('restaurant_campaign_recipients').select('campaign_id, notification_id').in('campaign_id', ids);
  const notifIds = (data ?? []).map((r) => r.notification_id).filter(Boolean) as string[];
  const { data: notes } = notifIds.length ? await admin.from('notifications').select('id, status').in('id', notifIds) : { data: [] };
  const status = new Map(((notes ?? []) as { id: string; status: string }[]).map((n) => [n.id, n.status]));
  for (const r of data ?? []) {
    const e = out.get(r.campaign_id) ?? { sent: 0, failed: 0, pending: 0 };
    const st = r.notification_id ? status.get(r.notification_id) : undefined;
    if (st === 'sent') e.sent += 1; else if (st === 'failed' || st === 'cancelled') e.failed += 1; else e.pending += 1;
    out.set(r.campaign_id, e);
  }
  return out;
}

