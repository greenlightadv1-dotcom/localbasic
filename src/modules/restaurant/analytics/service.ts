/**
 * Executive analytics reads and the campaign / settings writes (0110). Every
 * read is one SECURITY DEFINER function gated on
 * restaurant.analytics.executive (organization- or branch-wide); the
 * arithmetic on top lives in ./calc so it is tested once.
 */

type Rows = Record<string, unknown>[];
const num = (v: unknown) => (v === null || v === undefined ? 0 : Number(v));
const opt = (v: unknown) => (v === null || v === undefined ? null : Number(v));

async function rpc(fn: string, args: Record<string, unknown>, context: string): Promise<unknown> {
  const supabase = createSupabaseServerClient();
  const { data, error } = await supabase.rpc(fn as never, args as never);
  if (error) throw toDataUnavailable(error, context);
  return data;
}

