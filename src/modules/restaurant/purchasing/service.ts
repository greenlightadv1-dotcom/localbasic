import 'server-only';
import { z } from 'zod';
import { createSupabaseServerClient } from '@/lib/supabase/server';
import { staffDbError, toDataUnavailable } from '@/lib/errors';
import type { TenantContext } from '@/modules/core/tenancy/context';
import type { BaseUnit } from '@/modules/restaurant/inventory/units';

/**
 * Automated purchasing (0109): warehouse thresholds, reorder suggestions,
 * suppliers and purchase orders. The database decides what is low, what an
 * open order already covers and how much to buy; receiving books the stock in
 * through the same path as any purchase (moving-average cost).
 */

export type Suggestion = {
  itemId: string; name: string; unit: BaseUnit; onHand: number; minQty: number; reorderQty: number | null;
  openPoQty: number; suggestedQty: number; supplierId: string | null; unitCostCents: number;
};
export type Supplier = { id: string; name: string; phone: string | null; notes: string | null; isActive: boolean };
export type PurchaseOrder = {
  id: string; number: string; status: 'draft' | 'sent' | 'received' | 'cancelled'; supplierId: string | null;
  autoGenerated: boolean; note: string | null; expectedOn: string | null; createdAt: string; sentAt: string | null; receivedAt: string | null;
  lines: { itemId: string; qtyOrdered: number; unitCostCents: number; qtyReceived: number | null; receivedUnitCostCents: number | null }[];
  totalCents: number;
};
export type Threshold = { itemId: string; minQty: number; reorderQty: number | null; onHand: number; belowMin: boolean };
export type PurchasingItem = { id: string; name: string; unit: BaseUnit; avgCostCents: number; supplierId: string | null; isActive: boolean };

export async function getPurchasingBoard(ctx: TenantContext): Promise<{
  suggestions: Suggestion[]; orders: PurchaseOrder[]; suppliers: Supplier[]; thresholds: Threshold[]; items: PurchasingItem[];
}> {
  const supabase = createSupabaseServerClient();
  const since = new Date(Date.now() - 60 * 86_400_000).toISOString();
  const [sugg, orders, suppliers, thresholds, items] = await Promise.all([
    supabase.rpc('restaurant_reorder_suggestions' as never, { p_org: ctx.organizationId, p_branch: ctx.branchId } as never),
    supabase.from('restaurant_purchase_orders')
      .select('id, number, status, supplier_id, auto_generated, note, expected_on, created_at, sent_at, received_at')
      .eq('branch_id', ctx.branchId).or(`status.in.(draft,sent),created_at.gte.${since}`)
      .order('created_at', { ascending: false }).limit(100),
    supabase.from('restaurant_suppliers').select('id, name, phone, notes, is_active').eq('organization_id', ctx.organizationId).order('name'),
    supabase.from('restaurant_inventory_thresholds').select('inventory_item_id, min_stock_qty, reorder_qty, on_hand_qty, below_min')
      .eq('branch_id', ctx.branchId).eq('location_kind', 'warehouse'),
    supabase.from('inventory_items').select('id, name, unit, avg_cost_cents, preferred_supplier_id, is_active')
      .eq('organization_id', ctx.organizationId).order('name'),
  ]);
  if (sugg.error) throw toDataUnavailable(sugg.error, 'getPurchasingBoard suggestions');
  if (orders.error) throw toDataUnavailable(orders.error, 'getPurchasingBoard orders');
  const ids = (orders.data ?? []).map((o) => o.id);
  const { data: lines } = ids.length
    ? await supabase.from('restaurant_purchase_order_items')
        .select('purchase_order_id, item_id, qty_ordered, unit_cost_cents, qty_received, received_unit_cost_cents').in('purchase_order_id', ids)
    : { data: [] as never[] };
  const linesOf = (id: string) => ((lines ?? []) as {
    purchase_order_id: string; item_id: string; qty_ordered: number; unit_cost_cents: number; qty_received: number | null; received_unit_cost_cents: number | null;
  }[]).filter((l) => l.purchase_order_id === id).map((l) => ({
    itemId: l.item_id, qtyOrdered: Number(l.qty_ordered), unitCostCents: Number(l.unit_cost_cents),
    qtyReceived: l.qty_received === null ? null : Number(l.qty_received),
    receivedUnitCostCents: l.received_unit_cost_cents === null ? null : Number(l.received_unit_cost_cents),
  }));

  return {
    suggestions: ((sugg.data ?? []) as unknown as Record<string, unknown>[]).map((s) => ({
      itemId: String(s.out_item_id), name: String(s.out_name), unit: s.out_unit as BaseUnit, onHand: Number(s.out_on_hand),
      minQty: Number(s.out_min), reorderQty: s.out_reorder === null ? null : Number(s.out_reorder), openPoQty: Number(s.out_open_po),
      suggestedQty: Number(s.out_suggested), supplierId: (s.out_supplier_id as string) ?? null, unitCostCents: Number(s.out_unit_cost),
    })),
    orders: (orders.data ?? []).map((o) => {
      const l = linesOf(o.id);
      return {
        id: o.id, number: o.number, status: o.status, supplierId: o.supplier_id, autoGenerated: o.auto_generated, note: o.note,
        expectedOn: o.expected_on, createdAt: o.created_at, sentAt: o.sent_at, receivedAt: o.received_at, lines: l,
        totalCents: Math.round(l.reduce((s, x) => s + (x.qtyReceived ?? x.qtyOrdered) * (x.receivedUnitCostCents ?? x.unitCostCents), 0)),
      };
    }),
    suppliers: (suppliers.data ?? []).map((s) => ({ id: s.id, name: s.name, phone: s.phone, notes: s.notes, isActive: s.is_active })),
    thresholds: (thresholds.data ?? []).map((t) => ({
      itemId: t.inventory_item_id, minQty: Number(t.min_stock_qty), reorderQty: t.reorder_qty === null ? null : Number(t.reorder_qty),
      onHand: Number(t.on_hand_qty), belowMin: t.below_min,
    })),
    items: (items.data ?? []).map((i) => ({
      id: i.id, name: i.name, unit: i.unit, avgCostCents: Number(i.avg_cost_cents), supplierId: i.preferred_supplier_id, isActive: i.is_active,
    })),
  };
}

// ---------------------------------------------------------------------------
// Writes
// ---------------------------------------------------------------------------
async function call(fn: string, args: Record<string, unknown>, context: string): Promise<unknown> {
  const supabase = createSupabaseServerClient();
  const { data, error } = await supabase.rpc(fn as never, args as never);
  if (error) throw staffDbError(error, context);
  return data;
}

const qty = z.coerce.number().positive('الكمية يجب أن تكون أكبر من صفر').max(100_000_000);
const cost = z.coerce.number().min(0).max(1_000_000_000);

export const generateSchema = z.object({});
export async function generateOrders(ctx: TenantContext) {
  const r = (await call('restaurant_po_generate', { p_org: ctx.organizationId, p_branch: ctx.branchId }, 'generateOrders')) as {
    count: number; orders: { id: string; number: string; supplier_id: string | null; lines: number }[];
  };
  return { count: Number(r.count), orders: r.orders.map((o) => ({ id: o.id, number: o.number, supplierId: o.supplier_id, lines: o.lines })) };
}

export const poSaveSchema = z.object({
  id: z.string().uuid().nullable(),
  supplierId: z.string().uuid().nullable(),
  note: z.string().trim().max(500).optional(),
  expectedOn: z.string().regex(/^\d{4}-\d{2}-\d{2}$/).nullable().optional(),
  lines: z.array(z.object({ itemId: z.string().uuid(), qty, unitCostCents: cost.optional() })).min(1, 'أضف خامة واحدة على الأقل').max(200)
    .refine((l) => new Set(l.map((x) => x.itemId)).size === l.length, 'خامة مكررة في الطلب'),
});
export const savePo = async (ctx: TenantContext, i: z.infer<typeof poSaveSchema>) =>
  String(await call('restaurant_po_save', {
    p_org: ctx.organizationId, p_branch: ctx.branchId, p_po: i.id, p_supplier: i.supplierId, p_note: i.note ?? null,
    p_expected: i.expectedOn ?? null,
    p_lines: i.lines.map((l) => ({ item_id: l.itemId, qty: l.qty, unit_cost_cents: l.unitCostCents ?? null })),
  }, 'savePo'));

export const poStatusSchema = z.object({ id: z.string().uuid(), status: z.enum(['sent', 'cancelled']) });
export const setPoStatus = (ctx: TenantContext, i: z.infer<typeof poStatusSchema>) =>
  call('restaurant_po_set_status', { p_org: ctx.organizationId, p_po: i.id, p_status: i.status }, 'setPoStatus');

export const poReceiveSchema = z.object({
  id: z.string().uuid(),
  lines: z.array(z.object({ itemId: z.string().uuid(), qty: z.coerce.number().min(0).max(100_000_000), unitCostCents: cost.optional() })).min(1).max(200),
  note: z.string().trim().max(300).optional(),
});
export async function receivePo(ctx: TenantContext, i: z.infer<typeof poReceiveSchema>) {
  const r = (await call('restaurant_po_receive', {
    p_org: ctx.organizationId, p_po: i.id, p_note: i.note ?? null,
    p_lines: i.lines.map((l) => ({ item_id: l.itemId, qty: l.qty, unit_cost_cents: l.unitCostCents ?? null })),
  }, 'receivePo')) as { lines: number; total_cents: number };
  return { lines: Number(r.lines), totalCents: Number(r.total_cents) };
}

export const supplierSchema = z.object({
  id: z.string().uuid().nullable(), name: z.string().trim().min(1, 'اسم المورد مطلوب').max(160),
  phone: z.string().trim().max(30).optional(), notes: z.string().trim().max(500).optional(), isActive: z.boolean().default(true),
});
export const saveSupplier = async (ctx: TenantContext, i: z.infer<typeof supplierSchema>) =>
  String(await call('restaurant_supplier_save', {
    p_org: ctx.organizationId, p_id: i.id, p_name: i.name, p_phone: i.phone ?? null, p_notes: i.notes ?? null, p_active: i.isActive,
  }, 'saveSupplier'));

export const itemSupplierSchema = z.object({ itemId: z.string().uuid(), supplierId: z.string().uuid().nullable() });
export const setItemSupplier = (ctx: TenantContext, i: z.infer<typeof itemSupplierSchema>) =>
  call('inventory_item_set_supplier', { p_org: ctx.organizationId, p_item: i.itemId, p_supplier: i.supplierId }, 'setItemSupplier');

export const thresholdSchema = z.object({
  itemId: z.string().uuid(), kind: z.enum(['warehouse', 'kitchen', 'bar']).default('warehouse'),
  minQty: z.coerce.number().min(0).max(100_000_000).nullable(),
  reorderQty: z.coerce.number().positive().max(100_000_000).nullable(),
});
export const saveThreshold = (ctx: TenantContext, i: z.infer<typeof thresholdSchema>) =>
  call('inventory_threshold_save', {
    p_org: ctx.organizationId, p_branch: ctx.branchId, p_kind: i.kind, p_item: i.itemId, p_min_qty: i.minQty, p_reorder_qty: i.reorderQty,
  }, 'saveThreshold');
